const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const window = {};
const runtime = vm.createContext({window});
for (const script of ['spectral_lines.js','diagnostic_presets.js']) {
  vm.runInContext(fs.readFileSync(path.join(__dirname, '../cmfgen_viewer/static', script), 'utf8'), runtime);
}
const api = window.CmfgenDiagnosticPresets, lines = window.CmfgenSpectralLines;
const context = {halfWidth:3000, redshift:0, medium:'air', coverage:[3971,8747]};
const optical = api.plan('optical-wind', context);
assert.equal(optical.windows.length,2);
const halpha = optical.rows.find(row=>row.label==='Hα');
assert(halpha.min>6490 && halpha.min<6500);
assert(halpha.max>6620 && halpha.max<6640);
assert.equal(halpha.status,'available');
const shifted = api.plan('optical-wind',{...context,medium:'vacuum',redshift:.01});
const shiftedHalpha = shifted.rows.find(row=>row.label==='Hα');
assert(Math.abs(shiftedHalpha.min-6564.614*(1-3000/299792.458)*1.01)<1e-6);
const shiftedAir = api.plan('optical-wind',{...context,redshift:.01}).rows.find(row=>row.label==='Hα');
assert(Math.abs(shiftedAir.min-lines.vacuumToAir(shiftedHalpha.min))<1e-6);
const combined = api.plan('optical-combined',context);
assert.equal(combined.rows.length,6);
assert.equal(combined.windows.length,5, 'Broad neighboring He windows must merge');
assert(combined.windows.some(row=>row.label.includes('He I 4471 + He II 4542')));
for(let i=1;i<combined.windows.length;i++) assert(combined.windows[i-1].max<combined.windows[i].min);
const limited = api.plan('optical-combined',{...context,fitRange:[4828,5075]});
assert.equal(limited.windows.length,1);
assert.equal(limited.windows[0].label,'Hβ');
assert.equal(limited.rows.find(row=>row.label==='Hα').status,'outside fit range');
assert.equal(limited.rows.find(row=>row.label==='Hβ').status,'partially covered');
const uv = api.plan('uv-wind',context);
assert.equal(uv.windows.length,0);
assert(uv.rows.every(row=>row.status==='outside upload'));
assert.equal(api.plan('uv-wind',{...context,coverage:[900,1800]}).windows.length,3);
assert.equal(api.plan('fuv-wind',{...context,coverage:[900,1800]}).windows.length,1);
for (const [id, rowCount, windowCount] of [
  ['gosss-late-o',5,5], ['gosss-luminosity',4,4], ['gosss-of-ofc',3,2], ['gosss-vz',3,3]
]) {
  const selection = api.plan(id,{...context,halfWidth:undefined});
  assert.equal(selection.halfWidth,250);
  assert.equal(selection.rows.length,rowCount);
  assert.equal(selection.windows.length,windowCount);
  for(let i=1;i<selection.windows.length;i++) assert(selection.windows[i-1].max<selection.windows[i].min);
  const text = api.append('',selection).text;
  assert.equal(api.append(text,selection).added,0);
}
const late = api.plan('gosss-late-o',{...context,halfWidth:undefined});
const helium = late.rows.find(row=>row.label==='He II 4542');
const silicon = late.rows.find(row=>row.label==='Si III 4552');
assert(helium.max<silicon.min, 'Default classification windows must keep the 4542/4552 pair separate');
assert(helium.min<4541.59 && helium.max>4541.59);
assert(silicon.min<4552.62 && silicon.max>4552.62);
assert(api.plan('gosss-late-o',context).windows.length<5, 'An explicit broad width still overrides the classification default');
const lateVacuum = api.plan('gosss-late-o',{...context,halfWidth:undefined,redshift:.001,medium:'vacuum'});
const vacuumSilicon = lateVacuum.rows.find(row=>row.label==='Si III 4552');
assert(Math.abs(vacuumSilicon.min-lines.airToVacuum(4552.62)*(1-250/299792.458)*1.001)<1e-6);
const classificationMarkers = lines.referenceLines('air',0);
assert(classificationMarkers.some(row=>row.label==='Si III' && Math.abs(row.wavelength-4552.62)<1e-6));
assert(classificationMarkers.some(row=>row.label==='Si IV' && Math.abs(row.wavelength-4088.86)<1e-6));
assert(api.plan('gosss-vz',{...context,halfWidth:undefined}).description.includes('not calculated'));
const first = api.append('Manual, 6000, 6100\n',optical);
assert.equal(first.added,2);
assert(first.text.startsWith('Manual, 6000, 6100\n'));
assert.equal(api.append(first.text,optical).text,first.text, 'Repeated additions must not duplicate windows');
const partial = api.append('Keep my bounds, 6550, 6570',optical);
assert.equal(partial.added,1);
assert.equal(partial.skipped.length,1);
assert(partial.text.startsWith('Keep my bounds, 6550, 6570\n'));
assert.throws(()=>api.append('broken row',optical),/Fix diagnostic/);
assert.throws(()=>api.append('a, 6000, 6100\nb, 6050, 6150',optical),/overlap/);
assert.throws(()=>api.plan('unknown',context),/Choose/);
for(const width of [0,-1,NaN,Infinity,299792.458]) assert.throws(()=>api.plan('optical-wind',{...context,halfWidth:width}),/half-width/);
assert.throws(()=>api.plan('optical-wind',{...context,redshift:-1}),/redshift/);
assert.throws(()=>api.plan('optical-wind',{...context,fitRange:[6000,5000]}),/fit range/);
assert.throws(()=>api.plan('optical-wind',{...context,coverage:[Infinity,-Infinity]}),/load/);
const saved = first.text;
api.plan('optical-wind',{...context,redshift:.02});
assert.equal(first.text,saved, 'Changing source redshift must not move inserted windows');
console.log('PASS preset conversion, velocity bounds, coverage, merging, preservation, duplicates, and invalid input');
